#!/bin/bash
# Generate runtime configuration from the environment, then hand off to supervisord.
set -euo pipefail

log() { printf '[entrypoint] %s\n' "$*"; }

short_hostname() { hostname -s 2>/dev/null || hostname; }

# The speaker's name. Every other service defaults to it, so it is the only
# name that has to be set.
: "${AIRPLAY_NAME:=$(short_hostname)}"
: "${SENDSPIN_NAME:=${AIRPLAY_NAME}}"
: "${AIRPLAY_MODE:=airplay2}"
: "${AUDIO_SHARING:=dmix}"
: "${ALSA_PCM:=hw:0,0}"
: "${ALSA_RATE:=44100}"
: "${SHAIRPORT_OUTPUT_DEVICE:=default}"
: "${SENDSPIN_AUDIO_DEVICE:=default}"
: "${SENDSPIN_HARDWARE_VOLUME:=false}"
: "${WEB_PORT:=8080}"
: "${ENABLE_AIRPLAY:=1}"
: "${ENABLE_SENDSPIN:=1}"
: "${ENABLE_WEB:=1}"
: "${ENABLE_BLUETOOTH:=0}"
: "${BLUETOOTH_NAME:=${AIRPLAY_NAME}}"
: "${BLUETOOTH_ADAPTER:=hci0}"
: "${BLUETOOTH_AUDIO_DEVICE:=default}"
: "${BLUETOOTH_DISCOVERABLE:=1}"
: "${ENABLE_SPOTIFY:=0}"
: "${SPOTIFY_NAME:=${AIRPLAY_NAME}}"
: "${SPOTIFY_AUDIO_DEVICE:=default}"
: "${ENABLE_DLNA:=0}"
: "${DLNA_NAME:=${AIRPLAY_NAME}}"
: "${DLNA_PORT:=49494}"
: "${DLNA_AUDIO_DEVICE:=default}"
: "${DLNA_AUDIO_ONLY:=1}"
: "${EXTRA_SPOTIFYD_ARGS:=}"
: "${EXTRA_GMEDIARENDER_ARGS:=}"
: "${ENABLE_MQTT:=0}"
: "${LOG_LEVEL:=info}"
: "${AVAHI_MODE:=auto}"
: "${AVAHI_HOST_NAME:=}"
: "${AVAHI_INTERFACES:=}"
: "${AVAHI_PUBLISH_ADDRESSES:=auto}"
: "${EXTRA_SHAIRPORT_ARGS:=}"
: "${EXTRA_SENDSPIN_ARGS:=}"

CONF_D=/etc/supervisor/conf.d
# Our own system bus must never bind the shared /run/dbus path: in host mode that
# directory is the host's, and replacing its socket would break the host's D-Bus.
PRIVATE_SYSTEM_BUS=/run/sendspin-shareplay/system_bus_socket
mkdir -p "$CONF_D" /run/dbus /run/sendspin-shareplay /config/sendspin /var/lib/shairport-sync/coverart
rm -f "$CONF_D"/*.conf

##############################################################################
# ALSA
##############################################################################
write_asound_conf() {
    if [ -f /config/asound.conf ]; then
        log "using /config/asound.conf"
        cp /config/asound.conf /etc/asound.conf
        return
    fi

    case "$AUDIO_SHARING" in
        dmix)
            log "ALSA: dmix on ${ALSA_PCM} @ ${ALSA_RATE}Hz (both players share the device)"
            cat > /etc/asound.conf <<ASOUND
# Generated by entrypoint.sh -- mount /config/asound.conf to override.
# dmix lets Shairport Sync and Sendspin hold the output device at the same time.
pcm.sharedaudio {
    type plug
    slave.pcm "sendspin_shareplay_dmix"
    hint {
        show on
        description "Shared output (dmix)"
    }
}

pcm.sendspin_shareplay_dmix {
    type dmix
    ipc_key 3781
    ipc_perm 0666
    slave {
        pcm "${ALSA_PCM}"
        rate ${ALSA_RATE}
        channels 2
        format S16_LE
        period_size 1024
        buffer_size 8192
    }
    bindings {
        0 0
        1 1
    }
}

pcm.!default {
    type plug
    slave.pcm "sendspin_shareplay_dmix"
}

ctl.!default {
    type hw
    card 0
}
ASOUND
            ;;
        exclusive)
            log "ALSA: exclusive access to ${ALSA_PCM} (only one player can output at a time)"
            cat > /etc/asound.conf <<ASOUND
# Generated by entrypoint.sh -- mount /config/asound.conf to override.
pcm.!default {
    type plug
    slave.pcm "${ALSA_PCM}"
}

ctl.!default {
    type hw
    card 0
}
ASOUND
            ;;
        none)
            log "ALSA: not writing /etc/asound.conf (AUDIO_SHARING=none)"
            rm -f /etc/asound.conf
            ;;
        *)
            log "ERROR: AUDIO_SHARING must be one of dmix, exclusive, none (got '${AUDIO_SHARING}')"
            exit 1
            ;;
    esac
}

##############################################################################
# shairport-sync.conf
##############################################################################
write_shairport_conf() {
    if [ -f /config/shairport-sync.conf ]; then
        log "using /config/shairport-sync.conf"
        cp /config/shairport-sync.conf /etc/shairport-sync.conf
        return
    fi

    local mixer_line=""
    if [ -n "${ALSA_MIXER_CONTROL:-}" ]; then
        mixer_line="  mixer_control_name = \"${ALSA_MIXER_CONTROL}\";"
        if [ -n "${ALSA_MIXER_DEVICE:-}" ]; then
            mixer_line="${mixer_line}"$'\n'"  mixer_device = \"${ALSA_MIXER_DEVICE}\";"
        fi
    fi

    cat > /etc/shairport-sync.conf <<SPSCONF
// Generated by entrypoint.sh -- mount /config/shairport-sync.conf to override.
general = {
  name = "${AIRPLAY_NAME}";
  interpolation = "auto";
  // The web UI reads metadata over MPRIS, which must be on the same bus it is.
  dbus_service_bus = "session";
  mpris_service_bus = "session";
};

alsa = {
  output_device = "${SHAIRPORT_OUTPUT_DEVICE}";
${mixer_line}
};

metadata = {
  enabled = "yes";
  include_cover_art = "yes";
  cover_art_cache_directory = "/var/lib/shairport-sync/coverart";
  progress_interval = 1.0;
};

diagnostics = {
  log_verbosity = 0;
};
SPSCONF
}

##############################################################################
# mDNS
##############################################################################
# Every real network interface, which in practice means everything except
# loopback and the ones Docker creates. Avahi would otherwise announce the
# bridge addresses (172.x on docker0/br-*/veth*) to the LAN, and an AirPlay
# client that picks one of those simply fails to connect. A Pi on both Ethernet
# and Wi-Fi should advertise on both, so this is not narrowed to the default
# route's interface.
lan_interfaces() {
    local found="" name
    for path in /sys/class/net/*; do
        # bonding_masters is a file rather than an interface.
        [ -d "$path" ] || continue
        name="$(basename "$path")"
        case "$name" in
            # Docker's own, and the kernel's tunnel pseudo-devices.
            lo | docker* | br-* | veth* | virbr*) continue ;;
            gre* | erspan* | sit* | tunl* | ip6* | ip_vti* | dummy* | tun* | tap*) continue ;;
        esac
        found="${found:+$found,}${name}"
    done
    printf '%s' "$found"
}

# The sockets existing is not proof the daemon answers: the mount can be stale,
# Avahi can be built or configured without D-Bus, or the bus can refuse us.
# shairport-sync treats a failed Avahi client as fatal, so check before choosing.
# Any other mDNS responder already listening on 5353 in this network namespace:
# systemd-resolved, mDNSResponder, or another Avahi. Two responders cannot both
# own the host's address records -- they collide on the reverse PTR for the
# shared IP, which Avahi reports as a host name conflict and "resolves" by
# renaming itself, forever. 5353 == 0x14E9.
another_mdns_stack() {
    awk 'NR > 1 { split($2, a, ":"); if (a[2] == "14E9") { found = 1 } }
         END { exit !found }' /proc/net/udp /proc/net/udp6 2>/dev/null
}

avahi_on_the_bus() {
    [ -S /run/dbus/system_bus_socket ] || return 1
    dbus-send --system --dest=org.freedesktop.DBus --type=method_call --print-reply \
        /org/freedesktop/DBus org.freedesktop.DBus.NameHasOwner \
        string:org.freedesktop.Avahi 2>/dev/null | grep -q "boolean true"
}

resolve_avahi_mode() {
    case "$AVAHI_MODE" in
        host)
            if ! avahi_on_the_bus; then
                log "WARNING: AVAHI_MODE=host but org.freedesktop.Avahi does not answer on"
                log "  the system bus. Nothing will advertise. Check that avahi-daemon runs"
                log "  on the host and that /var/run/dbus is mounted."
            fi
            return
            ;;
        container) return ;;
    esac

    if avahi_on_the_bus; then
        AVAHI_MODE=host
        return
    fi

    AVAHI_MODE=container
    if [ -S /run/avahi-daemon/socket ] || [ -S /run/dbus/system_bus_socket ]; then
        log "NOTE: the host's D-Bus or Avahi socket is mounted, but Avahi does not answer"
        log "  on the bus, so a local avahi-daemon will run instead."
    fi
}

write_avahi_conf() {
    if [ -f /config/avahi-daemon.conf ]; then
        log "using /config/avahi-daemon.conf"
        cp /config/avahi-daemon.conf /etc/avahi/avahi-daemon.conf
        return
    fi


    # With another responder already on 5353, publishing our own address records
    # collides with it no matter what we are called. Publish services only and
    # let the existing stack answer for the host's address -- services still
    # resolve, because they point at the same host name it already owns.
    local publish_addresses="$AVAHI_PUBLISH_ADDRESSES"
    if [ "$publish_addresses" = "auto" ]; then
        if another_mdns_stack; then
            publish_addresses="no"
            log "another mDNS responder is already running on this host"
            log "  (systemd-resolved, most likely). Publishing services only, under"
            log "  \"$(short_hostname).local\", and leaving addresses to it."
            log "  For a cleaner setup, either run avahi-daemon on the host and mount"
            log "  its sockets, or turn off the other stack's mDNS."
        else
            publish_addresses="yes"
        fi
    fi

    local host_name_line=""
    if [ -n "$AVAHI_HOST_NAME" ]; then
        host_name_line="host-name=${AVAHI_HOST_NAME}"
    elif [ "$publish_addresses" = "no" ]; then
        # Services have to advertise the name the other responder publishes an
        # address for, or clients browse them and then fail to resolve.
        host_name_line="host-name=$(short_hostname)"
    fi
    local interfaces="${AVAHI_INTERFACES}"
    if [ -z "$interfaces" ]; then
        interfaces="$(lan_interfaces)"
    fi
    local allow_line=""
    if [ -n "$interfaces" ]; then
        allow_line="allow-interfaces=${interfaces}"
        log "Avahi will announce only on: ${interfaces}"
    else
        log "WARNING: found no LAN interfaces; Avahi will announce on all of them,"
        log "  including Docker's. Set AVAHI_INTERFACES to fix this."
    fi

    mkdir -p /etc/avahi
    cat > /etc/avahi/avahi-daemon.conf <<AVAHICONF
# Generated by entrypoint.sh -- mount /config/avahi-daemon.conf to override.
[server]
${host_name_line}
${allow_line}
use-ipv4=yes
use-ipv6=yes
ratelimit-interval-usec=1000000
ratelimit-burst=1000

[wide-area]
enable-wide-area=yes

[publish]
publish-addresses=${publish_addresses}
publish-hinfo=no
publish-workstation=no

[reflector]
enable-reflector=no

[rlimits]
rlimit-nproc=300
AVAHICONF
}

##############################################################################
# BlueZ
##############################################################################
write_bluetooth_conf() {
    # Pairing keys live here. Keeping them on the mounted volume means paired
    # phones survive a container rebuild instead of having to pair again.
    mkdir -p /config/bluetooth
    if [ ! -L /var/lib/bluetooth ]; then
        rm -rf /var/lib/bluetooth
        ln -s /config/bluetooth /var/lib/bluetooth
    fi

    if [ -f /config/bluetooth.conf ]; then
        log "using /config/bluetooth.conf"
        cp /config/bluetooth.conf /etc/bluetooth/main.conf
        return
    fi

    mkdir -p /etc/bluetooth
    cat > /etc/bluetooth/main.conf <<BTCONF
# Generated by entrypoint.sh -- mount /config/bluetooth.conf to override.
[General]
Name = ${BLUETOOTH_NAME}

# Audio/Video major class, Loudspeaker minor class, so phones show this as a
# speaker rather than as a generic computer.
Class = 0x200414

# Never stop being discoverable or pairable; there is no UI here to re-enable it.
DiscoverableTimeout = 0
PairableTimeout = 0
AlwaysPairable = true

# Phones routinely drop and re-derive keys; refusing to re-pair strands them.
JustWorksRepairing = always

FastConnectable = true

[Policy]
AutoEnable = true
ReconnectAttempts = 7
ReconnectIntervals = 1,2,4,8,16,32,64
BTCONF
}

##############################################################################
# supervisor programs
##############################################################################
program() {
    # program <name> <priority> <command...>
    local name="$1" priority="$2"; shift 2
    cat > "${CONF_D}/${name}.conf" <<PROG
[program:${name}]
command=$*
priority=${priority}
autostart=true
autorestart=true
startretries=1000000
stdout_logfile=/dev/fd/1
stdout_logfile_maxbytes=0
redirect_stderr=true
stopasgroup=true
killasgroup=true
environment=DBUS_SESSION_BUS_ADDRESS="unix:path=/run/sendspin-shareplay/session_bus_socket",${SYSTEM_BUS_ENV}PATH="/opt/venv/bin:/usr/local/bin:/usr/bin:/bin",HOME="/root"
PROG
}

resolve_avahi_mode

# program() bakes these into each supervisor entry, so they must be set before
# the first call.
if [ "$AVAHI_MODE" = "host" ]; then
    SYSTEM_BUS_SOCKET \
    ENABLE_MQTT MQTT_HOST MQTT_PORT MQTT_USERNAME MQTT_PASSWORD MQTT_TLS \
    MQTT_DEVICE_NAME MQTT_DEVICE_ID MQTT_BASE_TOPIC MQTT_DISCOVERY_PREFIX \
    MQTT_ART_BASE_URL MQTT_DIAGNOSTICS_INTERVAL=/run/dbus/system_bus_socket
    SYSTEM_BUS_ENV=""
else
    SYSTEM_BUS_SOCKET="$PRIVATE_SYSTEM_BUS"
    SYSTEM_BUS_ENV="DBUS_SYSTEM_BUS_ADDRESS=\"unix:path=${PRIVATE_SYSTEM_BUS}\","
fi
export SYSTEM_BUS_SOCKET

write_asound_conf
write_shairport_conf
if [ "$ENABLE_BLUETOOTH" = "1" ]; then
    write_bluetooth_conf
fi

program dbus-session 10 /usr/bin/dbus-daemon --session --nofork --nopidfile --address=unix:path=/run/sendspin-shareplay/session_bus_socket

if [ "$AVAHI_MODE" = "host" ]; then
    # The host's Avahi and D-Bus are mounted in. Running our own would fight the
    # host's daemon for the machine's .local name, renaming itself forever.
    log "mDNS: using the host's avahi-daemon"
else
    log "mDNS: running avahi-daemon inside the container"
    log "  If the host also runs avahi-daemon, the two will fight over the same"
    log "  .local name. Mount /var/run/dbus and /var/run/avahi-daemon instead --"
    log "  see the mDNS section of the README."
    write_avahi_conf
    # Only safe to clear when these are our daemons; in host mode the pid files
    # belong to the host's dbus and avahi.
    rm -f "$PRIVATE_SYSTEM_BUS" /run/avahi-daemon/pid
    program dbus-system 10 /usr/bin/dbus-daemon --system --nofork --nopidfile --address="unix:path=${PRIVATE_SYSTEM_BUS}"
    program avahi 20 /usr/local/bin/run-avahi.sh
fi

if [ "$ENABLE_AIRPLAY" = "1" ]; then
    if [ "$AIRPLAY_MODE" = "airplay2" ]; then
        program nqptp 20 /usr/local/bin/nqptp
    else
        log "AIRPLAY_MODE=${AIRPLAY_MODE}: running AirPlay 1 (classic), nqptp not started"
    fi
    program shairport-sync 30 /usr/local/bin/run-shairport-sync.sh
else
    log "AirPlay disabled (ENABLE_AIRPLAY=0)"
fi

if [ "$ENABLE_SENDSPIN" = "1" ]; then
    program sendspin 30 /usr/local/bin/run-sendspin.sh
else
    log "Sendspin disabled (ENABLE_SENDSPIN=0)"
fi

if [ "$ENABLE_BLUETOOTH" = "1" ]; then
    log "Bluetooth A2DP sink enabled as \"${BLUETOOTH_NAME}\" on ${BLUETOOTH_ADAPTER}"
    program bluetoothd 20 /usr/local/bin/run-bluetoothd.sh
    program bluealsa 25 /usr/local/bin/run-bluealsa.sh
    program bt-agent 30 /usr/local/bin/run-bt-agent.sh
    program bluealsa-aplay 35 /usr/local/bin/run-bluealsa-aplay.sh
fi

if [ "$ENABLE_SPOTIFY" = "1" ]; then
    log "Spotify Connect enabled as \"${SPOTIFY_NAME}\""
    mkdir -p /config/spotifyd
    program spotifyd 30 /usr/local/bin/run-spotifyd.sh
fi

if [ "$ENABLE_DLNA" = "1" ]; then
    log "DLNA/UPnP renderer enabled as \"${DLNA_NAME}\" on port ${DLNA_PORT}"
    program gmediarender 30 /usr/local/bin/run-gmediarender.sh
fi

if [ "$ENABLE_MQTT" = "1" ]; then
    if [ -z "${MQTT_HOST:-}" ]; then
        log "WARNING: ENABLE_MQTT=1 but MQTT_HOST is unset; MQTT stays off"
    else
        log "MQTT enabled: publishing to ${MQTT_HOST}:${MQTT_PORT:-1883}"
    fi
fi

if [ "$ENABLE_WEB" = "1" ]; then
    program web 40 /usr/local/bin/run-web.sh
else
    log "Web UI disabled (ENABLE_WEB=0)"
fi

dbus-uuidgen --ensure

# supervisord passes its own environment to the programs it starts, so anything
# defaulted above has to be exported to reach them.
export AIRPLAY_NAME SENDSPIN_NAME AIRPLAY_MODE AUDIO_SHARING ALSA_PCM ALSA_RATE \
    SHAIRPORT_OUTPUT_DEVICE SENDSPIN_AUDIO_DEVICE SENDSPIN_HARDWARE_VOLUME \
    WEB_PORT ENABLE_AIRPLAY ENABLE_SENDSPIN ENABLE_WEB LOG_LEVEL \
    EXTRA_SHAIRPORT_ARGS EXTRA_SENDSPIN_ARGS \
    ENABLE_BLUETOOTH BLUETOOTH_NAME BLUETOOTH_ADAPTER BLUETOOTH_AUDIO_DEVICE \
    BLUETOOTH_DISCOVERABLE \
    ENABLE_SPOTIFY SPOTIFY_NAME SPOTIFY_AUDIO_DEVICE SPOTIFY_BITRATE \
    SPOTIFY_INITIAL_VOLUME SPOTIFY_ZEROCONF_PORT EXTRA_SPOTIFYD_ARGS \
    ENABLE_DLNA DLNA_NAME DLNA_PORT DLNA_AUDIO_DEVICE DLNA_AUDIO_ONLY \
    DLNA_INTERFACE EXTRA_GMEDIARENDER_ARGS \
    AVAHI_MODE AVAHI_HOST_NAME AVAHI_INTERFACES AVAHI_PUBLISH_ADDRESSES \
    SYSTEM_BUS_SOCKET

log "shairport-sync ${SHAIRPORT_SYNC_VERSION:-?} / nqptp ${NQPTP_VERSION:-?} / sendspin ${SENDSPIN_VERSION:-?}"
log "AirPlay name: ${AIRPLAY_NAME}   Sendspin name: ${SENDSPIN_NAME}"

exec "$@"
